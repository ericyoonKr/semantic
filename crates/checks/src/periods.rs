// 법정 기간 계산 — 기산점 날짜에서 마감일 구하기 (PROJECT.md §7.2)
// dates.rs(날짜 글자 해석)와 나눈 이유: 이 파일은 민법의 기간 규정을 옮긴 법 규칙이라,
// 날짜 표기 형식이 늘어나는 것과는 따로 바뀐다.
//
// 담을 것:
// - fn deadline_days(start: NaiveDate, days: u32, holidays: &Holidays) -> NaiveDate
// - fn deadline_years(start: NaiveDate, years: u32, holidays: &Holidays) -> NaiveDate
//     (월 단위 기간이 필요해지면 deadline_months를 같은 방식으로)
// - struct Holidays — 연도별 공휴일 목록 (상수 또는 데이터 파일). 토요일 판정 포함.
//
// 적용 규칙 — 행정소송의 기간 계산은 민법을 따른다
// (행정소송법 제8조 제2항 → 민사소송법 제170조 → 민법):
// - 초일 불산입: 기간의 첫날은 넣지 않는다. 다만 오전 0시부터 시작하면 넣는다 (민법 제157조).
// - 주·월·연으로 정한 기간은 역에 따라 계산한다. 마지막 주·월·연에서 기산일에 해당하는 날의
//   전날로 끝나고, 그런 날이 없으면 그달의 말일로 끝난다 (민법 제160조).
//   → 1년을 365일로 바꿔 계산하지 않는다.
// - 기간의 말일이 토요일 또는 공휴일이면 그다음 날로 끝난다 (민법 제161조).
//
// 제소기간 (행정소송법 제20조) — 여기서는 기산점을 받아 마감일만 돌려준다.
// 어느 기산점을 쓸지는 요건 트리(rules/claim_취소소송.yaml)가 정한다:
// - 처분등이 있음을 안 날부터 90일 (제1항), 처분등이 있은 날부터 1년 (제2항)
// - 행정심판을 청구한 경우: 90일은 재결서 정본을 송달받은 날부터 (제1항 단서),
//   1년은 재결이 있은 날부터 (제2항 괄호)
// - 정당한 사유가 있으면 1년이 지나도 제기할 수 있다 (제2항 단서) — 계산이 아니라 리프 판정
//
// 쓰임: engine이 ArithSpec(WithinDays·WithinYears)의 마감일을 여기서 구해 ordinal로 Z3에 넣는다.
//       Finding을 내는 검증이 아니라 계산 도구라 run_all에는 들어가지 않는다.
// 규칙: Z3·LLM에 달력 계산을 시키지 않는다.
