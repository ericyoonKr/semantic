def _counts() -> tuple[int, int]:
    missed = sum(1 for text in INJECTED if not looks_injected(text))
    false_flags = sum(1 for text in CLEAN if looks_injected(text))
    return missed, false_flags


def test_injection_detector_accuracy() -> None:
    missed, false_flags = _counts()
    assert len(INJECTED) == 70 and len(CLEAN) == 90
    assert missed == 0, [t for t in INJECTED if not looks_injected(t)]
    assert false_flags == 0, [t for t in CLEAN if looks_injected(t)]
